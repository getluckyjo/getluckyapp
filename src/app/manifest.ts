import type { MetadataRoute } from 'next'
import { pwaAsset } from '@/lib/pwa/assets'

/**
 * Web app manifest, served at /manifest.webmanifest and linked by Next.
 *
 * start_url is /home, not /: the root page reads the session cookie and
 * redirects, which needs the network, so a cold launch from the icon with no
 * signal showed the browser's error page. /home renders a signed-out state
 * by itself and is in the worker's page cache, so the app shell comes up on
 * the course. It carries `source=pwa` so launches from the icon can be told
 * apart from browser visits; the analytics wrapper reads it there.
 * Icons are generated by `npm run pwa:assets` (scripts/pwa); their URLs
 * carry the asset version so a redesign reaches phones that cached the old one.
 */
export default function manifest(): MetadataRoute.Manifest {
  return {
    name: 'Get Lucky Hole in One Challenge',
    short_name: 'Get Lucky',
    description: 'Back yourself on any par-3. Record your hole-in-one and claim up to R1,000,000.',
    id: '/',
    start_url: '/home?source=pwa',
    scope: '/',
    display: 'standalone',
    orientation: 'portrait',
    theme_color: '#345231',
    background_color: '#345231',
    lang: 'en-ZA',
    categories: ['sports', 'games'],
    icons: [
      { src: pwaAsset('/icons/icon-192.png'), sizes: '192x192', type: 'image/png', purpose: 'any' },
      { src: pwaAsset('/icons/icon-256.png'), sizes: '256x256', type: 'image/png', purpose: 'any' },
      { src: pwaAsset('/icons/icon-384.png'), sizes: '384x384', type: 'image/png', purpose: 'any' },
      { src: pwaAsset('/icons/icon-512.png'), sizes: '512x512', type: 'image/png', purpose: 'any' },
      { src: pwaAsset('/icons/icon-maskable-512.png'), sizes: '512x512', type: 'image/png', purpose: 'maskable' },
    ],
  }
}
